ROW = re.compile(r"^\| `([A-Z]+) ([^`]+)`([^|]*)\|([^|]*)\| (W|M|P|\?) \| (\d) \| ([^|]*)\|", re.M)


def load_catalogue():
    """Return {"METHOD /path": op} merging variants (type=, formType=, channel=, kind=)."""
    text = (DOCS / "endpoint-catalogue.md").read_text(encoding="utf-8").split("## 14.")[0]
    ops = OrderedDict()
    section = None
    for line in text.splitlines():
        h = re.match(r"## (\d+)\. (.+)", line)
        if h:
            section = h.group(2).strip()
            continue
        m = ROW.match(line)
        if not m:
            continue
        method, raw_path, marks, fn, status, phase, owner = m.groups()
        key = norm(f"{method} {raw_path}")
        query = raw_path.split("?", 1)[1] if "?" in raw_path else ""
        variant = re.search(r"`([a-zA-Z]+)=([A-Z0-9_]+)`", marks)
        fn = re.sub(r"\*\*|`", "", fn).strip()
        op = ops.get(key)
        if op is None:
            op = ops[key] = {
                "method": method, "path": key.split(" ", 1)[1], "section": section, "summary": fn,
                "status": status, "phase": int(phase), "owner": owner.strip(), "money": False,
                "step_up": False, "query": [q.split("=")[0] for q in query.split("&") if q], "variants": [],
            }
        if STATUS_ORDER[status] < STATUS_ORDER[op["status"]]:
            op["status"], op["phase"] = status, int(phase)
        op["money"] |= "💰" in marks
        op["step_up"] |= "🔐" in marks
        if variant:
            op["variants"].append({"field": variant.group(1), "value": variant.group(2), "status": status,
                                   "phase": int(phase), "summary": fn})
    for ep in PLATFORM:
        method, path = ep.split(" ", 1)
        ops.setdefault(ep, {"method": method, "path": path, "section": "Platform (init.md §3.1)",
                            "summary": "Platform endpoint defined in init.md §3.1", "status": "W", "phase": 1,
                            "owner": platform_owner(path), "money": False, "step_up": False, "query": [], "variants": []})
    return ops


def platform_owner(path):
    return {"monitoring": "reporting", "ai": "intelligence", "audit": "audit", "ndc": "platform"}[path.split("/")[1]]


